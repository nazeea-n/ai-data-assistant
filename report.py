"""Builds the downloadable PDF report with ReportLab."""
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.lib.utils import ImageReader
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

import analysis
import charts

import matplotlib.pyplot as plt

STYLES = getSampleStyleSheet()
BODY = ParagraphStyle("body", parent=STYLES["BodyText"], fontSize=10, leading=14)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8, leading=10)


def _table(data, col_widths=None):
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4f8cff")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f2f5fb")]),
    ]))
    return t


def _figure_image(fig, width=14 * cm):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    buf.seek(0)
    w, h = ImageReader(buf).getSize()
    buf.seek(0)
    return Image(buf, width=width, height=width * h / w)


def _df_table(df, max_rows=15, round_to=2):
    shown = df.head(max_rows)
    rows = [list(map(str, shown.columns))]
    for _, r in shown.iterrows():
        rows.append([f"{v:.{round_to}f}" if isinstance(v, float) else str(v) for v in r])
    return _table(rows)


def build_pdf(df, filename="dataset", ai_summary=None):
    """Return the PDF as bytes."""
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=2 * cm, bottomMargin=2 * cm, title=f"Data report - {filename}")
    story = [Paragraph("Data Analysis Report", STYLES["Title"]),
             Paragraph(f"File: {escape(filename)}", BODY), Spacer(1, 10)]

    info = analysis.overview(df)
    story.append(Paragraph("1. Overview", STYLES["Heading2"]))
    story.append(_table([
        ["Rows", "Columns", "Numeric", "Text", "Date", "Missing cells", "Duplicate rows", "Quality score"],
        [info["rows"], info["columns"], info["numeric_columns"], info["text_columns"],
         info["date_columns"], info["missing_cells"], info["duplicate_rows"], f"{analysis.quality_score(df)}/100"],
    ]))

    story += [Spacer(1, 8), Paragraph("2. Key insights", STYLES["Heading2"])]
    for note in analysis.insights(df):
        story.append(Paragraph("&bull; " + escape(note), BODY))

    if ai_summary:
        story += [Spacer(1, 8), Paragraph("3. AI summary (Gemini)", STYLES["Heading2"])]
        for line in ai_summary.splitlines():
            if line.strip():
                story.append(Paragraph(escape(line.replace("**", "")), BODY))

    story += [Spacer(1, 8), Paragraph("4. Columns", STYLES["Heading2"]),
              _df_table(analysis.column_summary(df), max_rows=40)]

    missing = analysis.missing_report(df)
    if not missing.empty:
        story += [Spacer(1, 8), Paragraph("5. Missing values", STYLES["Heading2"]),
                  _df_table(missing), Spacer(1, 6), _figure_image(charts.missing_bar(df), 12 * cm)]

    stats = analysis.numeric_stats(df)
    if not stats.empty:
        keep = stats[["column", "mean", "std", "min", "median", "max", "skew"]]
        story += [Spacer(1, 8), Paragraph("6. Numeric statistics", STYLES["Heading2"]), _df_table(keep, 20)]

    outliers = analysis.find_outliers(df)
    if not outliers.empty:
        story += [Spacer(1, 8), Paragraph("7. Outliers (IQR rule)", STYLES["Heading2"]), _df_table(outliers)]

    story.append(Paragraph("8. Charts", STYLES["Heading2"]))
    numeric, text, _ = analysis.column_types(df)
    for col in numeric[:3]:
        story.append(_figure_image(charts.histogram(df, col), 12 * cm))
    for col in [c for c in text if 1 < df[c].nunique() <= 30][:2]:
        story.append(_figure_image(charts.top_categories_bar(df, col), 12 * cm))
    if len(numeric) >= 2:
        story.append(_figure_image(charts.correlation_heatmap(df), 12 * cm))

    story += [Spacer(1, 12), Paragraph("Generated by AI Data Analysis Assistant.", SMALL)]
    doc.build(story)
    return buf.getvalue()
